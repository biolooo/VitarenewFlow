#!/usr/bin/env python3
"""Generate installed/remote release highlights from one versioned DE/EN source."""
import argparse
import json
from pathlib import Path
import re


def load_notes(path, expected):
    value = json.loads(Path(path).read_text(encoding="utf-8"))
    if not re.fullmatch(r"[0-9]{1,3}\.[0-9]{1,3}\.[0-9]{1,3}", expected):
        raise ValueError("Invalid version")
    if type(value) is not dict or set(value) != {"version", "highlights"} or value["version"] != expected:
        raise ValueError("Release notes must match target version")
    rows = value["highlights"]
    if type(rows) is not list or not 1 <= len(rows) <= 3:
        raise ValueError("Expected one to three DE/EN highlights")
    for row in rows:
        if type(row) is not dict or set(row) != {"de", "en"}:
            raise ValueError("Both DE and EN are required")
        for text in row.values():
            if (type(text) is not str or not text.strip() or text != text.strip()
                    or len(text.encode("utf-8")) > 120
                    or any(ord(c) < 32 or 127 <= ord(c) <= 159 or ord(c) in (0xad,0x61c,0x180e,0x2028,0x2029,0xfeff)
                           or 0x200b <= ord(c) <= 0x200f or 0x202a <= ord(c) <= 0x202e
                           or 0x2060 <= ord(c) <= 0x206f for c in text)):
                raise ValueError("Invalid or overlong release highlight")
    return value


def sidecar(notes):
    lines = ["VFNOTES1", "version=" + notes["version"]]
    for row in notes["highlights"]:
        lines += ["de=" + row["de"], "en=" + row["en"]]
    return ("\n".join(lines) + "\n").encode("utf-8")


def header(notes):
    quote = lambda text: json.dumps(text, ensure_ascii=False)
    arrays = lambda lang: ",".join(quote(row[lang]) for row in notes["highlights"])
    return ("/* Generated by scripts/generate-release-notes.py; edit release-notes JSON. */\n"
            "#pragma once\n#include \"update_format.h\"\n"
            "static const UpdateNotes flow_release_notes={.version=" + quote(notes["version"])
            + ",.count=" + str(len(notes["highlights"])) + ",.de={" + arrays("de")
            + "},.en={" + arrays("en") + "}};\n").encode("utf-8")


def generate(root, version, check=False):
    notes = load_notes(Path(root) / "release-notes" / (version + ".json"), version)
    target = Path(root) / "launcher/source/release_notes_generated.h"
    data = header(notes)
    if check:
        if not target.exists() or target.read_bytes() != data:
            raise ValueError("Generated notes are missing/stale; run generator for target version")
    else:
        target.write_bytes(data)
    return notes


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--version", required=True)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--sidecar", type=Path, help="Write generated VFNOTES1 bytes to an explicit staging path")
    args = parser.parse_args()
    value = generate(args.root, args.version, args.check)
    if args.sidecar:
        args.sidecar.write_bytes(sidecar(value))
