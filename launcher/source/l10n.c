static bool readLanguage(const char *path,bool *value){
 FILE *f=fopen(path,"rb");if(!f)return false;
 int a=fgetc(f),b=fgetc(f),c=fgetc(f);bool ok=!ferror(f)&&(a=='0'||a=='1')&&b=='\n'&&c==EOF;
 if(fclose(f))ok=false;
 if(ok)*value=a=='1';
 return ok;
}
